export function isGuiLanguageLoaded(
	languageTag: SupportedGuiLanguageTag,
): boolean {
	return guiMessagesByLanguageTag[languageTag] !== undefined;
}

export function loadGuiMessages(
	languageTag: SupportedGuiLanguageTag,
): Promise<GuiMessages> {
	const loaded = guiMessagesByLanguageTag[languageTag];
	if (loaded) return Promise.resolve(loaded);
	const activeLoad = activeLoads.get(languageTag);
	if (activeLoad) return activeLoad;

	const load = guiMessageImporters[languageTag]()
		.then((module: GuiMessageModule) => module)
		.then(readGuiMessages)
		.then((messages) => {
			guiMessagesByLanguageTag[languageTag] = messages;
			return messages;
		})
		.finally(() => activeLoads.delete(languageTag));
	activeLoads.set(languageTag, load);
	return load;
}

export async function loadAllGuiLanguages(): Promise<void> {
	await Promise.all(supportedGuiLanguageTags.map(loadGuiMessages));
}

function readGuiMessages(module: GuiMessageModule): GuiMessages {
	const messages = Object.values(module).find(isGuiMessages);
	if (!messages) throw new Error("GUI language module has no message export");
	return messages;
}

function isGuiMessages(value: unknown): value is GuiMessages {
	return typeof value === "object" && value !== null && "common.back" in value;
}
